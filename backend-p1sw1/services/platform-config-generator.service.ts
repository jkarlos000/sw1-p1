  /**
   * Generate Windows main.cpp
   */
  private generateWindowsMainCpp(appName: string): string {
    return `#include <flutter/dart_project.h>
#include <flutter/flutter_view_controller.h>
#include <windows.h>

#include "utils.h"

int APIENTRY wWinMain(_In_ HINSTANCE instance, _In_opt_ HINSTANCE prev,
                      _In_ wchar_t *command_line, _In_ int show_command) {
  // Attach console on build and stderr so cout, cerr, clog can output to it.
  if (AttachConsole(ATTACH_PARENT_PROCESS)) {
    freopen("CONOUT\$", "w", stdout);
    freopen("CONOUT\$", "w", stderr);
    fprintf(stderr, "Visual Studio output window\\n");
  }

  // Initialize COM on the main thread.
  CoInitializeEx(nullptr, COINIT_APARTMENTTHREADED);

  flutter::DartProject project(L"data");

  std::vector<std::string> command_line_arguments =
      GetCommandLineArguments();

  project.set_dart_entrypoint_arguments(std::move(command_line_arguments));

  flutter::FlutterViewController controller(project);

  // Runs the Flutter application and returns when it ends.
  int result = controller.RunEventLoopWithWindowExit();

  CoUninitialize();

  return result;
}`;
  }

