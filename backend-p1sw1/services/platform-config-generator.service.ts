  /**
   * Validate platform configuration
   */
  validatePlatformConfig(platform: string, config: string): string[] {
    const errors: string[] = [];

    switch (platform.toLowerCase()) {
      case 'android':
        if (!config.includes('AndroidManifest.xml')) {
          errors.push('Missing AndroidManifest.xml configuration');
        }
        if (!config.includes('build.gradle')) {
          errors.push('Missing build.gradle configuration');
        }
        break;

      case 'ios':
        if (!config.includes('Info.plist')) {
          errors.push('Missing Info.plist configuration');
        }
        if (!config.includes('Podfile')) {
          errors.push('Missing Podfile configuration');
        }
        break;

      case 'web':
        if (!config.includes('index.html')) {
          errors.push('Missing index.html');
        }
        if (!config.includes('manifest.json')) {
          errors.push('Missing manifest.json');
        }
        break;

      default:
        errors.push(`Unknown platform: ${platform}`);
    }

    return errors;
  }
